//! Shell integration: shim generation, rc-file installation and removal.
//!
//! Interactive mode adds one marked block to the shell rc file (for fish, a
//! dedicated `conf.d` file). The block defines a function for each package
//! manager in [`zoli_pms::PackageManager::ALL`], and each function calls
//! `zoli wrap <pm> -- "$@"`. CI mode puts a directory of executable shims at
//! the front of `PATH`. Install and uninstall touch only the marked block.
//! See `docs/shell-integration.md`.

use anyhow::{Context, Result, bail, ensure};
use std::{
    io::Write,
    path::{Path, PathBuf},
};
use zoli_pms::PackageManager;

/// Opening marker for the rc-file block.
pub const BEGIN: &str = "# >>> zoli shims >>>";
/// Closing marker for the rc-file block.
pub const END: &str = "# <<< zoli shims <<<";
/// First line of every generated file. Uninstall uses it to avoid deleting a
/// file that Zoli did not create.
pub const HEADER: &str = "# Generated by zoli; do not edit. Run `zoli shims uninstall` to remove.";

const MAX_RC_BYTES: usize = 4 << 20;

/// A shell that receives interactive shims.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shell {
    /// GNU Bash.
    Bash,
    /// Z shell.
    Zsh,
    /// fish.
    Fish,
}

impl Shell {
    /// The rc file, relative to `$HOME`, that holds the marked block.
    pub const fn rc_file(self) -> &'static str {
        match self {
            Self::Bash => ".bashrc",
            Self::Zsh => ".zshrc",
            Self::Fish => ".config/fish/conf.d/zoli.fish",
        }
    }

    /// The shell name used in messages and generated file extensions.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Bash => "bash",
            Self::Zsh => "zsh",
            Self::Fish => "fish",
        }
    }

    /// The generated snippet extension.
    pub const fn extension(self) -> &'static str {
        self.name()
    }

    const fn uses_marked_block(self) -> bool {
        !matches!(self, Self::Fish)
    }
}

/// Paths written by an interactive install.
#[derive(Debug, Clone)]
pub struct Install {
    /// Generated function snippet, `$ZOLI_HOME/shims/zoli.<shell>`.
    pub generated: PathBuf,
    /// Shell rc file that sources the snippet.
    pub rc: PathBuf,
    /// Backup of the rc file, written before a change.
    pub backup: Option<PathBuf>,
    /// Whether any file content changed.
    pub changed: bool,
}

/// Paths written by a CI PATH install.
#[derive(Debug, Clone)]
pub struct CiInstall {
    /// Directory containing one executable shim per package manager.
    pub directory: PathBuf,
    /// Every shim path.
    pub shims: Vec<PathBuf>,
    /// Whether any file content changed.
    pub changed: bool,
}

fn quote(value: &Path) -> Result<String> {
    let text = value
        .to_str()
        .context("Zoli home path is not valid UTF-8")?;
    let mut out = String::from("\"");
    for character in text.chars() {
        match character {
            '\\' | '"' | '$' | '`' => {
                out.push('\\');
                out.push(character);
            }
            character if character.is_control() => {
                bail!("Zoli home path contains a control character")
            }
            character => out.push(character),
        }
    }
    out.push('"');
    Ok(out)
}

/// Bash/zsh/fish functions that call `zoli wrap`.
pub fn snippet(shell: Shell) -> String {
    let mut out = String::from(HEADER);
    out.push('\n');
    for manager in PackageManager::ALL {
        let program = manager.program();
        match shell {
            Shell::Bash | Shell::Zsh => {
                out.push_str(&format!(
                    "{program}() {{ command zoli wrap {program} -- \"$@\"; }}\n"
                ));
            }
            Shell::Fish => {
                out.push_str(&format!(
                    "function {program}\n    command zoli wrap {program} -- $argv\nend\n"
                ));
            }
        }
    }
    out
}

/// Generated snippet path for an interactive install.
pub fn generated_path(shell: Shell, zoli_home: &Path) -> PathBuf {
    zoli_home
        .join("shims")
        .join(format!("zoli.{}", shell.extension()))
}

/// CI shim directory.
pub fn ci_directory(zoli_home: &Path) -> PathBuf {
    zoli_home.join("shims").join("bin")
}

fn read_regular(path: &Path, limit: usize) -> Result<Option<Vec<u8>>> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) => {
            ensure!(
                metadata.file_type().is_file() && !metadata.file_type().is_symlink(),
                "refusing to read a non-regular file: {}",
                path.display()
            );
            ensure!(
                metadata.len() <= limit as u64,
                "file exceeds the size limit: {}",
                path.display()
            );
            Ok(Some(std::fs::read(path)?))
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
    }
}

fn create_private_directories(path: &Path) -> Result<()> {
    let mut missing = vec![];
    let mut current = path;
    loop {
        if current.exists() {
            break;
        }
        missing.push(current.to_path_buf());
        let Some(parent) = current.parent() else {
            break;
        };
        current = parent;
    }
    std::fs::create_dir_all(path)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        for directory in missing {
            std::fs::set_permissions(&directory, std::fs::Permissions::from_mode(0o700))?;
        }
    }
    Ok(())
}

fn write_atomic(path: &Path, bytes: &[u8], mode: u32, replace: bool) -> Result<bool> {
    if let Some(existing) = read_regular(path, usize::MAX)? {
        ensure!(
            replace,
            "refusing to overwrite an existing file: {}",
            path.display()
        );
        if existing == bytes {
            return Ok(false);
        }
    }
    let parent = path.parent().context("target directory is missing")?;
    create_private_directories(parent)?;
    let mut temporary = tempfile::NamedTempFile::new_in(parent)?;
    temporary.write_all(bytes)?;
    temporary.as_file().sync_all()?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        temporary
            .as_file()
            .set_permissions(std::fs::Permissions::from_mode(mode))?;
    }
    temporary.persist(path).map_err(|error| error.error)?;
    Ok(true)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Marker {
    Begin,
    End,
}

struct Line {
    start: usize,
    marker: Option<Marker>,
}

fn lines(bytes: &[u8]) -> Vec<Line> {
    let mut result = vec![];
    let mut start = 0;
    for index in 0..=bytes.len() {
        if index == bytes.len() || bytes[index] == b'\n' {
            let end = if index < bytes.len() {
                index + 1
            } else {
                index
            };
            let content = &bytes[start..index];
            let trimmed = content
                .iter()
                .position(|b| !b.is_ascii_whitespace())
                .map_or(&content[..0], |first| {
                    let last = content
                        .iter()
                        .rposition(|b| !b.is_ascii_whitespace())
                        .map_or(first, |last| last + 1);
                    &content[first..last]
                });
            let marker = if trimmed == BEGIN.as_bytes() {
                Some(Marker::Begin)
            } else if trimmed == END.as_bytes() {
                Some(Marker::End)
            } else {
                None
            };
            result.push(Line { start, marker });
            start = end;
        }
    }
    result
}

fn marker_count(bytes: &[u8]) -> usize {
    lines(bytes)
        .into_iter()
        .filter(|line| line.marker.is_some())
        .count()
}

fn marker_pair(bytes: &[u8]) -> Result<(usize, usize)> {
    let found: Vec<_> = lines(bytes)
        .into_iter()
        .filter_map(|line| line.marker.map(|marker| (marker, line.start)))
        .collect();
    match found.as_slice() {
        [(Marker::Begin, begin), (Marker::End, end)] if begin < end => Ok((*begin, *end)),
        [] => bail!("missing Zoli shim markers"),
        _ => bail!("Zoli shim markers are duplicated or out of order"),
    }
}

fn block(source: &str) -> String {
    format!("{BEGIN}\n[ -f {source} ] && . {source}\n{END}\n")
}

fn backup_path(rc: &Path) -> Result<PathBuf> {
    let name = rc.file_name().context("rc file name is missing")?;
    Ok(rc.with_file_name(format!("{}.zoli-backup", name.to_string_lossy())))
}

fn install_marked(shell: Shell, home: &Path, zoli_home: &Path) -> Result<Install> {
    let generated = generated_path(shell, zoli_home);
    let rc = home.join(shell.rc_file());
    let source = quote(&generated)?;
    let existing = read_regular(&rc, MAX_RC_BYTES)?;
    let updated = match &existing {
        None => block(&source).into_bytes(),
        Some(bytes) if marker_count(bytes) == 0 => {
            let mut value = bytes.clone();
            if !value.is_empty() && !value.ends_with(b"\n") {
                value.push(b'\n');
            }
            value.extend_from_slice(block(&source).as_bytes());
            value
        }
        Some(bytes) => {
            let (begin, end) = marker_pair(bytes)?;
            let closing = bytes[end..]
                .iter()
                .position(|byte| *byte == b'\n')
                .map_or(bytes.len(), |index| end + index + 1);
            let mut value = Vec::with_capacity(bytes.len() + 128);
            value.extend_from_slice(&bytes[..begin]);
            value.extend_from_slice(block(&source).as_bytes());
            value.extend_from_slice(&bytes[closing..]);
            value
        }
    };
    let backup = match &existing {
        Some(bytes) => {
            let path = backup_path(&rc)?;
            write_atomic(&path, bytes, 0o600, true)?;
            Some(path)
        }
        None => None,
    };
    let generated_changed = write_atomic(&generated, snippet(shell).as_bytes(), 0o600, true)?;
    let rc_changed = write_atomic(&rc, &updated, 0o600, true)?;
    Ok(Install {
        generated,
        rc,
        backup,
        changed: rc_changed || generated_changed,
    })
}

fn uninstall_marked(shell: Shell, home: &Path, zoli_home: &Path) -> Result<Option<PathBuf>> {
    let generated = generated_path(shell, zoli_home);
    let rc = home.join(shell.rc_file());
    let Some(existing) = read_regular(&rc, MAX_RC_BYTES)? else {
        remove_generated(&generated)?;
        return Ok(None);
    };
    if marker_count(&existing) == 0 {
        remove_generated(&generated)?;
        return Ok(None);
    }
    let (begin, end) = marker_pair(&existing)?;
    let closing = existing[end..]
        .iter()
        .position(|byte| *byte == b'\n')
        .map_or(existing.len(), |index| end + index + 1);
    let mut updated = Vec::with_capacity(existing.len());
    updated.extend_from_slice(&existing[..begin]);
    updated.extend_from_slice(&existing[closing..]);
    let path = backup_path(&rc)?;
    write_atomic(&path, &existing, 0o600, true)?;
    write_atomic(&rc, &updated, 0o600, true)?;
    remove_generated(&generated)?;
    Ok(Some(path))
}

fn remove_generated(path: &Path) -> Result<()> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) => {
            ensure!(
                metadata.file_type().is_file() && !metadata.file_type().is_symlink(),
                "refusing to remove a non-regular file: {}",
                path.display()
            );
            std::fs::remove_file(path)?;
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error.into()),
    }
    Ok(())
}

/// Install interactive shell functions. Idempotent; the rc file is backed up
/// before any change and only Zoli's marked block is edited.
pub fn install(shell: Shell, home: &Path, zoli_home: &Path) -> Result<Install> {
    if shell.uses_marked_block() {
        return install_marked(shell, home, zoli_home);
    }
    let generated = generated_path(shell, zoli_home);
    let rc = home.join(shell.rc_file());
    let existing = read_regular(&rc, MAX_RC_BYTES)?;
    if let Some(bytes) = &existing {
        ensure!(
            bytes.starts_with(HEADER.as_bytes()),
            "refusing to overwrite an existing fish conf.d file that Zoli did not create: {}",
            rc.display()
        );
    }
    let backup = match &existing {
        Some(bytes) => {
            let path = backup_path(&rc)?;
            write_atomic(&path, bytes, 0o600, true)?;
            Some(path)
        }
        None => None,
    };
    let source = quote(&generated)?;
    let contents = format!("{HEADER}\ntest -f {source}; and source {source}\n");
    let generated_changed = write_atomic(&generated, snippet(shell).as_bytes(), 0o600, true)?;
    let rc_changed = write_atomic(&rc, contents.as_bytes(), 0o600, true)?;
    Ok(Install {
        generated,
        rc,
        backup,
        changed: rc_changed || generated_changed,
    })
}

/// Remove interactive shell functions. Idempotent; unrelated rc content and
/// files that Zoli did not generate are preserved.
pub fn uninstall(shell: Shell, home: &Path, zoli_home: &Path) -> Result<Option<PathBuf>> {
    if shell.uses_marked_block() {
        return uninstall_marked(shell, home, zoli_home);
    }
    let generated = generated_path(shell, zoli_home);
    let rc = home.join(shell.rc_file());
    if let Some(existing) = read_regular(&rc, MAX_RC_BYTES)? {
        ensure!(
            existing.starts_with(HEADER.as_bytes()),
            "refusing to remove a fish conf.d file that Zoli did not create: {}",
            rc.display()
        );
        let path = backup_path(&rc)?;
        write_atomic(&path, &existing, 0o600, true)?;
        std::fs::remove_file(&rc)?;
        remove_generated(&generated)?;
        return Ok(Some(path));
    }
    remove_generated(&generated)?;
    Ok(None)
}

/// Install executable PATH shims for scripts, CI and IDE tasks.
pub fn install_ci(zoli_home: &Path) -> Result<CiInstall> {
    let directory = ci_directory(zoli_home);
    let mut shims = vec![];
    let mut changed = false;
    for manager in PackageManager::ALL {
        let path = directory.join(manager.program());
        let program = manager.program();
        let contents = format!(
            "#!/bin/sh\n# Generated by zoli; do not edit.\nexec zoli wrap {program} -- \"$@\"\n"
        );
        changed |= write_atomic(&path, contents.as_bytes(), 0o755, true)?;
        shims.push(path);
    }
    Ok(CiInstall {
        directory,
        shims,
        changed,
    })
}

/// Remove only the known PATH shims and the directory when it becomes empty.
pub fn uninstall_ci(zoli_home: &Path) -> Result<bool> {
    let directory = ci_directory(zoli_home);
    let mut changed = false;
    for manager in PackageManager::ALL {
        let path = directory.join(manager.program());
        match std::fs::symlink_metadata(&path) {
            Ok(metadata) => {
                ensure!(
                    metadata.file_type().is_file() && !metadata.file_type().is_symlink(),
                    "refusing to remove a non-regular file: {}",
                    path.display()
                );
                std::fs::remove_file(&path)?;
                changed = true;
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(error.into()),
        }
    }
    match std::fs::remove_dir(&directory) {
        Ok(()) => changed = true,
        Err(error)
            if matches!(
                error.kind(),
                std::io::ErrorKind::NotFound | std::io::ErrorKind::DirectoryNotEmpty
            ) => {}
        Err(error) => return Err(error.into()),
    }
    Ok(changed)
}

/// Append one directory to an existing `$GITHUB_PATH` file, idempotently.
pub fn append_path_file(path: &Path, directory: &Path) -> Result<bool> {
    let existing = read_regular(path, 1 << 20)?.unwrap_or_default();
    let line = directory.to_str().context("shim path is not UTF-8")?;
    if String::from_utf8_lossy(&existing)
        .lines()
        .any(|candidate| candidate == line)
    {
        return Ok(false);
    }
    let mut file = std::fs::OpenOptions::new().append(true).open(path)?;
    if !existing.is_empty() && !existing.ends_with(b"\n") {
        file.write_all(b"\n")?;
    }
    file.write_all(line.as_bytes())?;
    file.write_all(b"\n")?;
    Ok(true)
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
mod tests {
    use super::*;

    #[test]
    fn snippets_cover_every_manager() {
        for shell in [Shell::Bash, Shell::Zsh, Shell::Fish] {
            let text = snippet(shell);
            for manager in PackageManager::ALL {
                assert!(text.contains(manager.program()), "{}: {text}", shell.name());
            }
            assert!(text.starts_with(HEADER));
        }
        assert!(snippet(Shell::Bash).contains("npm() { command zoli wrap npm -- \"$@\"; }"));
        assert!(
            snippet(Shell::Fish).contains("function npm\n    command zoli wrap npm -- $argv\nend")
        );
    }

    #[test]
    fn bash_install_is_idempotent_and_backs_up() {
        let home = tempfile::tempdir().unwrap();
        let zoli = tempfile::tempdir().unwrap();
        std::fs::write(home.path().join(".bashrc"), b"export ORIGINAL=1\n").unwrap();
        let first = install(Shell::Bash, home.path(), zoli.path()).unwrap();
        assert!(first.changed);
        assert_eq!(
            first.backup.as_deref(),
            Some(home.path().join(".bashrc.zoli-backup").as_path())
        );
        let rc = std::fs::read_to_string(home.path().join(".bashrc")).unwrap();
        assert!(rc.starts_with("export ORIGINAL=1\n"));
        assert_eq!(rc.matches(BEGIN).count(), 1);
        assert_eq!(rc.matches(END).count(), 1);
        assert!(rc.contains("zoli.bash"));
        assert!(first.generated.exists());
        assert_eq!(
            std::fs::read_to_string(home.path().join(".bashrc.zoli-backup")).unwrap(),
            "export ORIGINAL=1\n"
        );
        let second = install(Shell::Bash, home.path(), zoli.path()).unwrap();
        assert!(!second.changed);
        assert_eq!(
            std::fs::read_to_string(home.path().join(".bashrc")).unwrap(),
            rc
        );
        uninstall(Shell::Bash, home.path(), zoli.path()).unwrap();
        assert_eq!(
            std::fs::read_to_string(home.path().join(".bashrc")).unwrap(),
            "export ORIGINAL=1\n"
        );
        assert!(!first.generated.exists());
        uninstall(Shell::Bash, home.path(), zoli.path()).unwrap();
    }

    #[test]
    fn unbalanced_markers_are_refused_without_changes() {
        let home = tempfile::tempdir().unwrap();
        let zoli = tempfile::tempdir().unwrap();
        let original = format!("{BEGIN}\nnot closed\n");
        std::fs::write(home.path().join(".zshrc"), &original).unwrap();
        assert!(install(Shell::Zsh, home.path(), zoli.path()).is_err());
        assert_eq!(
            std::fs::read_to_string(home.path().join(".zshrc")).unwrap(),
            original
        );
        assert!(!generated_path(Shell::Zsh, zoli.path()).exists());
    }

    #[test]
    fn replacing_an_existing_block_does_not_grow_the_file() {
        let home = tempfile::tempdir().unwrap();
        let zoli = tempfile::tempdir().unwrap();
        install(Shell::Bash, home.path(), zoli.path()).unwrap();
        let first = std::fs::read_to_string(home.path().join(".bashrc")).unwrap();
        let second = install(Shell::Bash, home.path(), zoli.path()).unwrap();
        assert!(!second.changed);
        assert_eq!(
            std::fs::read_to_string(home.path().join(".bashrc")).unwrap(),
            first
        );
    }

    #[test]
    fn fish_uses_a_dedicated_conf_file() {
        let home = tempfile::tempdir().unwrap();
        let zoli = tempfile::tempdir().unwrap();
        install(Shell::Fish, home.path(), zoli.path()).unwrap();
        let rc = home.path().join(".config/fish/conf.d/zoli.fish");
        let text = std::fs::read_to_string(&rc).unwrap();
        assert!(text.starts_with(HEADER));
        assert!(text.contains("source"));
        uninstall(Shell::Fish, home.path(), zoli.path()).unwrap();
        assert!(!rc.exists());
    }

    #[test]
    fn ci_shims_are_executable_and_uninstall_keeps_foreign_files() {
        let zoli = tempfile::tempdir().unwrap();
        let installed = install_ci(zoli.path()).unwrap();
        assert_eq!(installed.shims.len(), PackageManager::ALL.len());
        let foreign = installed.directory.join("keep-me");
        std::fs::write(&foreign, b"keep").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            for shim in &installed.shims {
                assert!(
                    std::fs::metadata(shim).unwrap().permissions().mode() & 0o111 != 0,
                    "{}",
                    shim.display()
                );
            }
        }
        assert!(uninstall_ci(zoli.path()).unwrap());
        assert_eq!(std::fs::read_to_string(&foreign).unwrap(), "keep");
        assert!(!installed.shims[0].exists());
    }

    #[test]
    fn github_path_is_appended_once() {
        let zoli = tempfile::tempdir().unwrap();
        let directory = ci_directory(zoli.path());
        let file = tempfile::NamedTempFile::new().unwrap();
        std::fs::write(file.path(), "/existing").unwrap();
        assert!(append_path_file(file.path(), &directory).unwrap());
        assert!(!append_path_file(file.path(), &directory).unwrap());
        let text = std::fs::read_to_string(file.path()).unwrap();
        assert_eq!(text, format!("/existing\n{}\n", directory.display()));
    }
}
